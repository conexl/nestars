export type Translations = typeof dict.en

const typedDict: Record<Lang, Translations> = dict

export function getDict(lang: Lang): Translations {
  return typedDict[lang] ?? typedDict.en
}

export function normalizeLang(code?: string): Lang {
  if (!code) return 'en'
  return code.toLowerCase().startsWith('ru') ? 'ru' : 'en'
}
